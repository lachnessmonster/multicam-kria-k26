#!/bin/bash
# IMX219 1080p RAW10, 2-lane, 912 Mbps init + stream on
BUS=6
ADDR=0x10
w() { sudo i2ctransfer -y $BUS w3@$ADDR $(printf '0x%02x 0x%02x 0x%02x' $((($1>>8)&0xff)) $(($1&0xff)) $2); }

# stream off before reconfig
w 0x0100 0x00

# access-code / common
w 0x30eb 0x05; w 0x30eb 0x0c; w 0x300a 0xff; w 0x300b 0xff; w 0x30eb 0x05; w 0x30eb 0x09
w 0x0114 0x01   # 2 data lanes
w 0x0128 0x00
w 0x012a 0x18   # INCK 24MHz
w 0x012b 0x00

# CSI data format = RAW10  (THE fix that was missing)
w 0x0112 0x0a; w 0x0113 0x0a

# frame/line timing
w 0x0162 0x0d; w 0x0163 0x78

# crop window (1920x1080)
w 0x0164 0x02; w 0x0165 0xa8
w 0x0166 0x0a; w 0x0167 0x27
w 0x0168 0x02; w 0x0169 0xb4
w 0x016a 0x06; w 0x016b 0xeb
w 0x016c 0x07; w 0x016d 0x80
w 0x016e 0x04; w 0x016f 0x38
w 0x0170 0x01; w 0x0171 0x01
w 0x0174 0x00; w 0x0175 0x00
w 0x018c 0x0a; w 0x018d 0x0a   # output data format 10-bit

# PLL (24MHz -> 912 Mbps/lane)
w 0x0301 0x05; w 0x0303 0x01
w 0x0304 0x03; w 0x0305 0x03
w 0x0306 0x00; w 0x0307 0x39
w 0x0309 0x0a; w 0x030b 0x01
w 0x030c 0x00; w 0x030d 0x72

# recommended tuning
w 0x0624 0x07; w 0x0625 0x80; w 0x0626 0x04; w 0x0627 0x38
w 0x455e 0x00; w 0x471e 0x4b; w 0x4767 0x0f; w 0x4750 0x14
w 0x4540 0x00; w 0x47b4 0x14

# exposure + gain defaults
w 0x0157 0x80              # analog gain
w 0x015a 0x03; w 0x015b 0xe8  # exposure

# stream on
w 0x0100 0x01
echo "imx219 streaming (RAW10 1080p)"
